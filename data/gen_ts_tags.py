#!/usr/bin/env python3
"""Generate the TypeScript tag data for the Worker from ytutil.py / pass2.py.

Reads the normalized keyword->tag pairs (KW_NORM) and the channel topic tags,
then replaces the marker `// __TAG_DATA__` in the Worker's src/index.ts with
a compact generated block. Run after any change to build.py's keywords or
pass2.py's topic tags:

    python3 data/gen_ts_tags.py

The generated block is data only (a compact string + a small object); the
tagging functions (normTitle/tagsForTitle/videoTagsFor) live in src/index.ts.
Keywords are emitted already normalized, so the TS side only normalizes the
title — identical matching to Python's tags_for_title().
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ytutil  # noqa: E402
from pass2 import CHANNEL_TOPIC_TAGS  # noqa: E402

WORKER = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                      "..", "worker", "src", "index.ts")
MARKER = "// __TAG_DATA__"


def main():
    # KW_NORM is [(normalized keyword, tag), ...] — already normalized.
    pairs = [(k, t) for k, t in ytutil.KW_NORM]
    raw = "|".join(f"{k}:{t}" for k, t in pairs)
    # Safety: keywords/tags must not contain the delimiters.
    assert ":" not in "".join(t for _, t in pairs) and "|" not in "".join(
        t for _, t in pairs), "tag contains a delimiter"
    assert all(":" not in k and "|" not in k for k, _ in pairs), \
        "keyword contains a delimiter"
    topics = ", ".join(
        f"{i}: [{', '.join(repr(t) for t in tags)}]"
        for i, tags in sorted(CHANNEL_TOPIC_TAGS.items()))
    block = (
        "// Generated by data/gen_ts_tags.py from ytutil.py (KW_NORM) and\n"
        "// pass2.py (CHANNEL_TOPIC_TAGS) — do not edit by hand. Re-run the\n"
        "// generator after any change to build.py's keywords or pass2.py.\n"
        "// Keyword -> tag pairs, normalized, as \"kw:tag|kw:tag|...\".\n"
        f"const TAG_KEYWORDS_RAW = {raw!r};\n"
        "const TAG_KEYWORDS: [string, string][] = TAG_KEYWORDS_RAW.split('|').map((p) => {\n"
        "  const i = p.indexOf(':')\n"
        "  return [p.slice(0, i), p.slice(i + 1)] as [string, string]\n"
        "})\n"
        "// Channel index -> curated topic tag(s) (pass-2 fallback).\n"
        f"const CHANNEL_TOPIC_TAGS: Record<number, string[]> = {{ {topics} }};"
    )
    src = open(WORKER).read()
    assert MARKER in src, f"marker {MARKER!r} not found in {WORKER}"
    assert src.count(MARKER) == 1, "marker must appear exactly once"
    open(WORKER, "w").write(src.replace(MARKER, block))
    print(f"wrote {len(pairs)} keyword pairs + "
          f"{len(CHANNEL_TOPIC_TAGS)} channel topic tags into {WORKER}")


if __name__ == "__main__":
    main()
